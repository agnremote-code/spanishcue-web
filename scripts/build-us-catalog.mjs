// Regenerates app/us-content/catalog.generated.ts from public/us-content/<family>/*.json.
// Only slug, level, title and theme go into the bundle; bodies stay in assets.
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';

export function readCatalog(root = process.cwd()) {
  const base = resolve(root, 'public/us-content');
  if (!existsSync(base)) return [];
  return readdirSync(base, { withFileTypes: true }).filter(d => d.isDirectory()).flatMap(family =>
    readdirSync(resolve(base, family.name)).filter(f => f.endsWith('.json')).sort().map(file => {
      const page = JSON.parse(readFileSync(resolve(base, family.name, file), 'utf8'));
      return { family: family.name, slug: file.replace(/\.json$/, ''), level: page.level ?? '', theme: page.theme ?? '', title: page.h1 ?? page.title };
    }));
}

export function catalogSource(entries) {
  return `// Generated by scripts/build-us-catalog.mjs. Do not edit by hand.\nexport type UsCatalogEntry = { family: string; slug: string; level: string; theme: string; title: string };\nexport const usCatalog: UsCatalogEntry[] = ${JSON.stringify(entries, null, 1)};\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(resolve(process.cwd(), 'app/us-content/catalog.generated.ts'), catalogSource(readCatalog()));
  console.log(`us-content catalog: ${readCatalog().length} pages`);
}
