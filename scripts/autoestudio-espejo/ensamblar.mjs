// Assembles the mirrored Autoestudio course after the weeks are written:
// 1. curriculum/objectives/<level>.ts from docs/autoestudio-espejo/objetivos/<level>-wNN.json
// 2. reviewObjectives + prerequisites of every module (spaced repetition):
//    core week N reviews everything taught in week N-1 (week 1 reviews the previous
//    level's week 20); checkpoints review the four previous weeks.
// Usage: node scripts/autoestudio-espejo/ensamblar.mjs [level…]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
const LEVELS = ['a1', 'a2', 'b1', 'b2', 'c1', 'c2'];
const only = process.argv.slice(2);
const pad = (w) => `w${String(w).padStart(2, '0')}`;
const rowsOf = (level, week) => {
  const file = `docs/autoestudio-espejo/objetivos/${level}-${pad(week)}.json`;
  return existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : null;
};
const idsOf = (level, week) => (rowsOf(level, week) ?? []).map((r) => `${level}.${r[1]}.${r[2]}`);
const names = { a1: 'a1Objectives', a2: 'a2Objectives', b1: 'b1Objectives', b2: 'b2Objectives', c1: 'c1Objectives', c2: 'c2Objectives' };
for (const level of LEVELS) {
  if (only.length && !only.includes(level)) continue;
  const rows = [];
  for (let week = 1; week <= 20; week++) {
    const r = rowsOf(level, week);
    if (!r) throw new Error(`missing objectives ${level} week ${week}`);
    rows.push(...r);
  }
  writeFileSync(`app/autoestudio/curriculum/objectives/${level}.ts`, `import { defineObjectives } from "../define";

/**
 * ${level.toUpperCase()} — Autoestudio espejo: each week reviews the grammar classes of
 * docs/autoestudio-espejo/mapa.json. Generated by scripts/autoestudio-espejo/ensamblar.mjs
 * from docs/autoestudio-espejo/objetivos/${level}-wNN.json. Do not edit by hand.
 */
export const ${names[level]} = defineObjectives("${level}", ${JSON.stringify(rows, null, 1)});
`);
  for (let week = 1; week <= 20; week++) {
    const file = `app/autoestudio/curriculum/modules/${level}/${pad(week)}.ts`;
    let src = readFileSync(file, 'utf8');
    const checkpoint = week % 5 === 0;
    let review = [];
    let prereq = [];
    const previousLevel = LEVELS[LEVELS.indexOf(level) - 1];
    if (week === 1) {
      if (previousLevel) { review = idsOf(previousLevel, 20); prereq = [`${previousLevel}-20`]; }
    } else {
      for (let w = checkpoint ? Math.max(1, week - 4) : week - 1; w < week; w++) review.push(...idsOf(level, w));
      prereq = [`${level}-${String(week - 1).padStart(2, '0')}`];
    }
    const before = src;
    src = src.replace(/"?reviewObjectives"?:\s*\[[^\]]*\]/, `reviewObjectives: ${JSON.stringify(review)}`);
    src = src.replace(/(\n  )"?prerequisites"?:\s*\[[^\]]*\]/, `$1prerequisites: ${JSON.stringify(prereq)}`);
    if (src === before && (review.length || prereq.length)) console.warn(`${file}: nothing replaced`);
    writeFileSync(file, src);
  }
  console.log(`${level}: assembled`);
}
