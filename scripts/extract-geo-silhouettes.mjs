// Writes the outlines of a country's 3D regions for the floating islands of
// its map, from a GeoJSON file (lon/lat): each region fits a 20 m square,
// x east, z south. Usage:
//   node scripts/extract-geo-silhouettes.mjs <in.geo.json> <out.mjs> "Name A" "Name B" …
import { readFileSync, writeFileSync } from 'node:fs';

const [input, output, ...names] = process.argv.slice(2);
const geo = JSON.parse(readFileSync(input, 'utf8'));
const area = pts => Math.abs(pts.reduce((s, [x, y], i) => { const [x2, y2] = pts[(i + 1) % pts.length]; return s + x * y2 - x2 * y; }, 0) / 2);
function simplify(pts, tol) {
  if (pts.length < 4) return pts;
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop(); let best = -1, at = -1;
    const [ax, ay] = pts[a], [bx, by] = pts[b]; const len = Math.hypot(bx - ax, by - ay) || 1;
    for (let i = a + 1; i < b; i++) { const d = Math.abs((bx - ax) * (ay - pts[i][1]) - (ax - pts[i][0]) * (by - ay)) / len; if (d > best) { best = d; at = i; } }
    if (best > tol) { keep[at] = 1; stack.push([a, at], [at, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}
const out = {};
for (const name of names) {
  const f = geo.features.find(x => x.properties.name === name);
  if (!f) throw new Error(`${name} is not in ${input}`);
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  const lat0 = polys.flat(2).reduce((s, p) => s + p[1], 0) / polys.flat(2).length;
  // Equirectangular around the region's latitude; screen y grows south.
  const proj = ([lon, lat]) => [lon * Math.cos((lat0 * Math.PI) / 180), -lat];
  let rings = polys.map(p => p[0].map(proj));
  const biggest = Math.max(...rings.map(area));
  rings = rings.filter(r => area(r) > biggest * 0.02).sort((a, b) => area(b) - area(a)).slice(0, 8);
  const all = rings.flat(); const xs = all.map(p => p[0]), ys = all.map(p => p[1]);
  const cx = (Math.min(...xs) + Math.max(...xs)) / 2, cy = (Math.min(...ys) + Math.max(...ys)) / 2;
  const span = Math.max(Math.max(...xs) - Math.min(...xs), Math.max(...ys) - Math.min(...ys));
  const k = 20 / span;
  const closed = (r, tol) => { const mid = Math.floor(r.length / 2); return [...simplify(r.slice(0, mid + 1), tol).slice(0, -1), ...simplify(r.slice(mid), tol)]; };
  out[name] = rings.map(r => closed(r, span / 160).map(([x, y]) => [+((x - cx) * k).toFixed(2), +((y - cy) * k).toFixed(2)]));
}
writeFileSync(output, `// Generated by scripts/extract-geo-silhouettes.mjs from ${input}:\n// each region fits a 20 m square, x east, z south. Do not edit by hand.\nexport const SILUETAS = ${JSON.stringify(out)};\n`);
console.log(Object.fromEntries(Object.entries(out).map(([k, v]) => [k, v.map(r => r.length)])));
