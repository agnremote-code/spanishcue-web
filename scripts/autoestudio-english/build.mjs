// Copies reviewed translations (one JSON per week: Spanish → English) into
// app/autoestudio/english and regenerates the index. Fails if any learner-facing
// A1–B2 string has no English or if markup/gaps do not survive translation.
// Usage: node scripts/autoestudio-english/build.mjs <folder with a1-w01.json…>
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { loadCourse } from './load.mjs';
import { englishKey, moduleTexts, problems, BILINGUAL_LEVELS } from './fields.mjs';

// Without a folder, rebuilds from the Spanish-keyed sources kept in the scratch
// input; the committed files are hash-keyed and cannot be re-read as sources.
const source = process.argv[2];
if (!source) throw new Error('usage: build.mjs <folder with Spanish-keyed a1-w01.json…>');
const { modulesByLevel } = await loadCourse();
const index = [];
let failures = 0;
for (const level of BILINGUAL_LEVELS) {
  for (const mod of modulesByLevel[level]) {
    const name = `w${String(mod.week).padStart(2, '0')}`;
    const target = `app/autoestudio/english/${level}/${name}.json`;
    const from = `${source}/${level}-${name}.json`;
    const dict = existsSync(from) ? JSON.parse(readFileSync(from, 'utf8')) : {};
    const kept = {};
    for (const es of moduleTexts(mod)) {
      const issues = problems(es, dict[es]);
      if (issues.length) { failures++; console.error(`${level}-${name}: ${issues.join(',')}: ${JSON.stringify(es).slice(0, 120)}`); continue; }
      const key = englishKey(es);
      if (key in kept) { failures++; console.error(`${level}-${name}: key collision: ${es.slice(0, 80)}`); continue; }
      // Spanish kept on purpose (a cited form, a model answer) needs no English line.
      if (dict[es].trim() !== es) kept[key] = dict[es].trim();
    }
    mkdirSync(`app/autoestudio/english/${level}`, { recursive: true });
    writeFileSync(target, JSON.stringify(kept, null, 1) + '\n');
    index.push({ level, week: mod.week, name });
  }
}
const imports = index.map(({ level, name }) => `import ${level}${name} from "./${level}/${name}.json";`).join('\n');
const table = BILINGUAL_LEVELS.map(level => `  ${level}: [${index.filter(i => i.level === level).map(i => `${level}${i.name}`).join(', ')}],`).join('\n');
writeFileSync('app/autoestudio/english/index.ts', `// Generated by scripts/autoestudio-english/build.mjs. Do not edit by hand.
import type { LevelId } from "../curriculum/types";
${imports}

const weeks: Partial<Record<LevelId, Readonly<Record<string, string>>[]>> = {
${table}
};

/** Spanish → English lines for one Autoestudio week; undefined at C1–C2 (Spanish-only). */
export function englishFor(level: LevelId, week: number): Readonly<Record<string, string>> | undefined {
  return weeks[level]?.[week - 1];
}
`);
console.log(failures ? `ENGLISH: ${failures} strings missing or broken` : 'ENGLISH: complete');
process.exitCode = failures ? 1 : 0;
