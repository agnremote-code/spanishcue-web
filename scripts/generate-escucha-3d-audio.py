#!/usr/bin/env python3
"""Build the Comprensión auditiva audio for the 3D games from
app/escucha-3d/content/<game>/<level>.json with Edge neural voices from many
Spanish-speaking countries. Runs in GitHub Actions (.github/workflows/
escucha-3d-audio.yml): the content hash in audio-manifest.json skips clips
that did not change. Requires edge-tts and ffmpeg."""
import asyncio, hashlib, json, pathlib, subprocess, sys
import edge_tts

ROOT = pathlib.Path(__file__).resolve().parents[1]
CONTENT = ROOT / 'app/escucha-3d/content'
OUT = ROOT / 'public/audio/escucha-3d'
MANIFEST = ROOT / 'app/escucha-3d/audio-manifest.json'
RATE = {'A0': '-22%', 'A1': '-14%', 'A2': '-7%', 'B1': '-3%', 'B2': '+0%', 'C1': '+0%', 'C2': '+4%'}
SR = 24000
VERSION = 1
sem = asyncio.Semaphore(4)


def pcm_of(mp3: bytes) -> bytes:
    return subprocess.run(['ffmpeg', '-v', 'error', '-i', 'pipe:0', '-f', 's16le', '-ar', str(SR), '-ac', '1', 'pipe:1'],
                          input=mp3, capture_output=True, check=True).stdout


async def speak(text, voice, rate):
    for attempt in range(5):
        try:
            chunks = []
            async for message in edge_tts.Communicate(text, voice, rate=rate).stream():
                if message['type'] == 'audio':
                    chunks.append(message['data'])
            data = b''.join(chunks)
            if data:
                return data
        except Exception as error:  # network hiccups: retry
            print(f'retry {attempt + 1} {voice}: {error}', flush=True)
        await asyncio.sleep(2 + attempt * 3)
    raise RuntimeError(f'Could not synthesize with {voice}: {text[:60]}')


async def clip(game, level, item, key, digest):
    async with sem:
        rate = RATE[level]
        pause_same = b'\0\0' * int(SR * (0.35 if level in ('A0', 'A1') else 0.22))
        pause_turn = b'\0\0' * int(SR * (0.7 if level in ('A0', 'A1') else 0.45))
        pcm = bytearray(b'\0\0' * int(SR * 0.3))
        last = None
        for line in item['lines']:
            voice = item['speakers'][line['s']]['voice']
            if last is not None:
                pcm += pause_turn if line['s'] != last else pause_same
            pcm += pcm_of(await speak(line['text'], voice, rate))
            last = line['s']
        pcm += b'\0\0' * int(SR * 0.4)
        dest = OUT / f"{game}-{level.lower()}-{item['id']}.mp3"
        dest.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-f', 's16le', '-ar', str(SR), '-ac', '1', '-i', 'pipe:0',
                        '-af', 'loudnorm=I=-17:TP=-1.5:LRA=11', '-ar', str(SR), '-codec:a', 'libmp3lame', '-b:a', '40k', str(dest)],
                       input=bytes(pcm), check=True)
        seconds = round(len(pcm) / 2 / SR, 2)
        print(f'{key} {seconds}s', flush=True)
        return key, {'hash': digest, 'seconds': seconds, 'src': f"/audio/escucha-3d/{game}-{level.lower()}-{item['id']}.mp3"}


async def main():
    manifest = json.loads(MANIFEST.read_text()) if MANIFEST.exists() else {'clips': {}}
    old = manifest.get('clips', {})
    jobs, keep = [], {}
    for path in sorted(CONTENT.glob('*/*.json')):
        data = json.loads(path.read_text())
        game, level = data['game'], data['level']
        for item in data['items']:
            key = f"{game}/{level.lower()}-{item['id']}"
            digest = hashlib.sha256(json.dumps([VERSION, RATE[level], item['speakers'], item['lines']], sort_keys=True, ensure_ascii=False).encode()).hexdigest()[:20]
            dest = OUT / f"{game}-{level.lower()}-{item['id']}.mp3"
            if old.get(key, {}).get('hash') == digest and dest.exists():
                keep[key] = old[key]
            else:
                jobs.append(clip(game, level, item, key, digest))
    print(f'{len(jobs)} clips to build, {len(keep)} unchanged', flush=True)
    results = await asyncio.gather(*jobs)
    clips = {**keep, **dict(results)}
    for mp3 in OUT.glob('*.mp3'):
        if mp3.stem.replace('-', '/', 1) not in clips:
            mp3.unlink()
    MANIFEST.write_text(json.dumps({'producer': 'Edge neural voices (es-*), generated by scripts/generate-escucha-3d-audio.py', 'clips': dict(sorted(clips.items()))}, ensure_ascii=False, indent=1) + '\n')
    print(f'Done: {len(clips)} clips', flush=True)

asyncio.run(main())
