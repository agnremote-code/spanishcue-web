// Writes app/estados-unidos-a2-b1/mundo/siluetas.mjs: the outlines of the
// states that have a 3D zone, taken from the real U.S. Census boundaries the
// 50-state atlas already uses (states-albers-10m.json), centred and in metres
// for the floating islands of the 3D map. Run after adding a state.
import { readFileSync, writeFileSync } from 'node:fs';

const STATES = ['Florida', 'New York', 'California', 'Texas', 'Hawaii', 'Colorado'];
const topology = JSON.parse(readFileSync('app/estados-unidos-a2-b1/states-albers-10m.json', 'utf8'));
const arcs = topology.arcs.map(arc => { let x = 0, y = 0; return arc.map(([dx, dy]) => { x += dx; y += dy; return [x * topology.transform.scale[0] + topology.transform.translate[0], y * topology.transform.scale[1] + topology.transform.translate[1]]; }); });
const arcPoints = i => i < 0 ? [...arcs[~i]].reverse() : arcs[i];
const ring = indices => indices.flatMap((i, part) => part ? arcPoints(i).slice(1) : arcPoints(i));
const area = pts => Math.abs(pts.reduce((s, [x, y], i) => { const [x2, y2] = pts[(i + 1) % pts.length]; return s + x * y2 - x2 * y; }, 0) / 2);
// Douglas–Peucker keeps the recognisable coastlines with few points.
function simplify(pts, tol) {
  if (pts.length < 4) return pts;
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop(); let best = -1, at = -1;
    const [ax, ay] = pts[a], [bx, by] = pts[b]; const len = Math.hypot(bx - ax, by - ay) || 1;
    for (let i = a + 1; i < b; i++) { const d = Math.abs((bx - ax) * (ay - pts[i][1]) - (ax - pts[i][0]) * (by - ay)) / len; if (d > best) { best = d; at = i; } }
    if (best > tol) { keep[at] = 1; stack.push([a, at], [at, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}
const out = {};
for (const name of STATES) {
  const g = topology.objects.states.geometries.find(x => x.properties.name === name);
  const polys = g.type === 'Polygon' ? [g.arcs] : g.arcs;
  let rings = polys.map(p => ring(p[0])).filter(r => area(r) > 1.5).sort((a, b) => area(b) - area(a)).slice(0, 8);
  const all = rings.flat(); const xs = all.map(p => p[0]), ys = all.map(p => p[1]);
  const cx = (Math.min(...xs) + Math.max(...xs)) / 2, cy = (Math.min(...ys) + Math.max(...ys)) / 2;
  const span = Math.max(Math.max(...xs) - Math.min(...xs), Math.max(...ys) - Math.min(...ys));
  // Every island fits in a 20 m square; x east, z south (screen y down).
  const k = 20 / span;
  const closed = (r, tol) => { const mid = Math.floor(r.length / 2); return [...simplify(r.slice(0, mid + 1), tol).slice(0, -1), ...simplify(r.slice(mid), tol)]; };
  out[name] = rings.map(r => closed(r, span / 160).map(([x, y]) => [+((x - cx) * k).toFixed(2), +((y - cy) * k).toFixed(2)]));
}
writeFileSync('app/estados-unidos-a2-b1/mundo/siluetas.mjs', `// Generated by scripts/extract-usa-silhouettes.mjs from the U.S. Census\n// boundaries of states-albers-10m.json: each state fits a 20 m square,\n// x east, z south. Do not edit by hand.\nexport const SILUETAS = ${JSON.stringify(out)};\n`);
console.log(Object.fromEntries(Object.entries(out).map(([k, v]) => [k, v.map(r => r.length)])));
