import test from 'node:test';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {runInNewContext} from 'node:vm';
import {build} from 'esbuild';
import {JSDOM} from 'jsdom';
const require=createRequire(import.meta.url),dom=new JSDOM('<div id="root"></div>',{url:'https://spanishcue.com/the-sound-map'});
Object.assign(globalThis,{window:dom.window,document:dom.window.document,HTMLElement:dom.window.HTMLElement,IS_REACT_ACT_ENVIRONMENT:true});
let loads=0;
dom.window.HTMLMediaElement.prototype.pause=function(){};
dom.window.HTMLMediaElement.prototype.load=function(){loads++;};
const React=require('react'),{act}=React,{createRoot}=require('react-dom/client');
const result=await build({entryPoints:['app/listening-studio/AudioDeck.tsx'],bundle:true,write:false,format:'cjs',platform:'node',jsx:'automatic',external:['react'],loader:{'.css':'empty'}});
const loaded={exports:{}};runInNewContext(`(function(require,module,exports){${result.outputFiles[0].text}\n})`,{window:dom.window,document:dom.window.document})(require,loaded,loaded.exports);
const root=createRoot(document.getElementById('root'));
test('bilingual audio failures have an in-place retry and preserve usable translated controls',async()=>{
 await act(async()=>root.render(React.createElement(loaded.exports.default,{src:'/a.mp3',title:'Audio',channel:'City',bilingual:true,allowSlow:true})));
 const el=document.querySelector('audio');
 await act(async()=>el.dispatchEvent(new dom.window.Event('error')));
 assert.match(document.body.textContent,/Retry/);
 const retry=[...document.querySelectorAll('button')].find(x=>x.textContent.includes('Retry'));
 assert.ok(retry&&!retry.disabled);const before=loads;
 await act(async()=>retry.dispatchEvent(new dom.window.MouseEvent('click',{bubbles:true})));
 assert.ok(loads>before);
 Object.defineProperty(el,'duration',{value:12,configurable:true});
 await act(async()=>el.dispatchEvent(new dom.window.Event('loadedmetadata')));
 assert.equal(document.querySelector('.audio-play').disabled,false);
 assert.match(document.body.textContent,/Repeat/);
 await act(async()=>root.unmount());dom.window.close();
});
