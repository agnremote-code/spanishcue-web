import assert from 'node:assert/strict';
import test from 'node:test';
import {JSDOM} from 'jsdom';
const origin=process.env.CHESPANISH_TEST_ORIGIN || 'http://127.0.0.1:8787';
test('the long guide «materiales para enseñar español» is a full indexable article for anonymous visitors',async()=>{
 const path='/material-ele/guia/materiales-para-ensenar-espanol';
 const response=await fetch(origin+path);assert.equal(response.status,200);
 assert.equal(response.headers.get('cache-control'),'public, max-age=0, must-revalidate');assert.ok(!response.headers.has('set-cookie'));
 const dom=new JSDOM(await response.text());const d=dom.window.document;
 assert.equal(d.documentElement.lang,'es');
 assert.equal(d.querySelectorAll('h1').length,1);assert.match(d.querySelector('h1').textContent,/Materiales para enseñar español/);
 assert.equal(d.title,'Materiales para enseñar español: guía completa para profesores | SpanishCue');
 assert.equal(d.querySelector('link[rel="canonical"]').href,'https://spanishcue.com'+path);
 assert.doesNotMatch(d.querySelector('meta[name="robots"]')?.content||'',/noindex/);
 assert.match(d.querySelector('meta[property="og:image"]').content,/^https:\/\/spanishcue\.com\//);
 const schemas=[...d.querySelectorAll('script[type="application/ld+json"]')].map(s=>JSON.parse(s.textContent));
 for(const type of ['BreadcrumbList','FAQPage'])assert.ok(schemas.some(s=>s['@type']===type),type);
 const page=schemas.find(s=>s['@type']==='WebPage');assert.equal(page.inLanguage,'es');assert.equal(page.datePublished,'2026-11-02');assert.ok(page.image);
 const main=d.querySelector('main');
 assert.ok(main.querySelectorAll('h2').length>=8,'sections');assert.ok(main.querySelectorAll('h3').length>=5,'levels');
 assert.ok(main.querySelectorAll('article').length>=6);
 assert.ok(main.querySelector('strong'),'bold runs render as elements');assert.doesNotMatch(main.textContent,/\*\*|\]\(/,'no raw markdown');
 assert.ok(main.querySelector('a[href="/material-ele/gramatica/preterito-indefinido"]'),'internal topic link');
 assert.ok(main.querySelector('a[href="/gramatica/clase-inicial"]'),'free class link');
 assert.ok(main.querySelector('a[href="/pricing"]'),'buy link');assert.match(main.textContent,/US\$19,90 al mes/);
 assert.match(main.textContent,/Descargar ficha en PDF/);assert.match(main.textContent,/Publicado el/);
 assert.ok(main.querySelector('video')||main.querySelector('figure'),'class preview');
 assert.ok(d.querySelector('footer a[href="/material-ele"]'));
 const hub=await (await fetch(origin+'/material-ele')).text();assert.ok(hub.includes(`href="${path}"`),'hub links the guide');
 dom.window.close();
});
test('unknown long guide is a 404',async()=>{assert.equal((await fetch(origin+'/material-ele/guia/no-existe')).status,404);});
for(const path of ['/material-ele/guia/preparar-una-clase-de-espanol-rapido','/material-ele/guia/fichas-ele-para-imprimir-y-proyectar','/material-ele/guia/actividades-de-conversacion-en-espanol-para-adultos','/material-ele/guia/ejercicios-ele-con-soluciones','/material-ele/guia/como-dar-clases-de-espanol-online'])test(`long guide renders as an indexable article: ${path}`,async()=>{
 const response=await fetch(origin+path);assert.equal(response.status,200);
 const dom=new JSDOM(await response.text());const d=dom.window.document;
 assert.equal(d.querySelectorAll('h1').length,1);assert.equal(d.querySelector('link[rel="canonical"]').href,'https://spanishcue.com'+path);
 const main=d.querySelector('main');assert.ok(main.querySelectorAll('h2').length>=7);assert.doesNotMatch(main.textContent,/\*\*|\]\(/);
 assert.ok(main.querySelector('a[href="/pricing"]'));assert.match(main.textContent,/Publicado el/);
 const home=await (await fetch(origin+'/')).text();assert.ok(home.includes(`href="${path}"`),'home links the guide');
 dom.window.close();
});
