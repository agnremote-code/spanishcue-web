// The clock of the night: 23:15 with nothing played, 06:10 when every circle is done.
export function nightClock(done, total = STORY.length) {
  const start = TRIP.start[0] * 60 + TRIP.start[1];
  const end = TRIP.end[0] * 60 + TRIP.end[1] + 24 * 60;
  const k = Math.max(0, Math.min(1, done / total));
  const minutes = Math.round((start + (end - start) * k) / 5) * 5 % (24 * 60);
  return `${String(Math.floor(minutes / 60)).padStart(2, '0')}:${String(minutes % 60).padStart(2, '0')}`;
}

// The boarding pass after the circles played at this level.
export function boardingPass(done) {
  const rebooked = done.includes('reprogramacion');
  const boarded = done.includes('puerta');
  if (boarded) return { state: 'abordo', flight: TRIP.rebooked.flight, time: TRIP.rebooked.time, gate: TRIP.rebooked.gate, seat: TRIP.seat, label: 'Embarque confirmado' };
  if (rebooked) return { state: 'espera', flight: TRIP.rebooked.flight, time: TRIP.rebooked.time, gate: TRIP.rebooked.gate, seat: null, label: 'Lista de espera' };
  return { state: 'cancelado', flight: TRIP.cancelled.flight, time: TRIP.cancelled.time, gate: null, seat: null, label: 'Cancelado' };
}
