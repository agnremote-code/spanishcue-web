const dictionaries = { es, en } as const;

export function dashT(locale: DashLocale, key: DashKey, values?: Record<string, string>): string {
  let text: string = dictionaries[locale][key] ?? es[key];
  if (values) for (const [name, value] of Object.entries(values)) text = text.replaceAll(`{${name}}`, value);
  return text;
}

export function dateLabel(locale: DashLocale, value: string | number | null | undefined, withTime = false): string {
  if (value === null || value === undefined || value === "") return dashT(locale, "common.never");
  const date = typeof value === "number" ? new Date(value * 1000) : new Date(value);
  if (Number.isNaN(date.getTime())) return dashT(locale, "common.never");
  return date.toLocaleString(locale === "es" ? "es-ES" : "en-US", withTime ? { dateStyle: "medium", timeStyle: "short" } : { dateStyle: "medium" });
}

