export const messages: Record<Locale, Record<MessageKey, string>> = { es, en };

const categoryKeys: Record<string, MessageKey> = {
  Gramática: "category.grammar",
  Conversación: "category.conversation",
  Escucha: "category.listening",
  Fonética: "category.pronunciation",
  Vocabulario: "category.vocabulary",
};

export function normalizeLocale(value: string | null | undefined): Locale | null {
  if (!value) return null;
  const normalized = value.trim().toLowerCase().split(/[-_]/)[0];
  return normalized === "es" || normalized === "en" ? normalized : null;
}

export function localeFromHeaders(headers: Headers): Locale {
  const explicit = normalizeLocale(headers.get("x-spanishcue-locale"));
  if (explicit) return explicit;
  const cookie = headers.get("cookie") || "";
  const match = cookie.match(/(?:^|;\s*)spanishcue_locale=(es|en)(?:;|$)/i);
  const saved = normalizeLocale(match?.[1]);
  if (saved) return saved;
  const pathname = headers.get("x-spanishcue-pathname")?.replace(/\/+$/, "") || "/";
  if ([
    "/spanish-teacher-resources",
    "/spanish-conversation-activities",
    "/spanish-grammar-lessons",
    "/online-spanish-teaching-resources",
    "/free-spanish-lesson",
  ].includes(pathname)) return "en";
  return DEFAULT_LOCALE;
}

export function translate(
  locale: Locale,
  key: MessageKey,
  values: Record<string, string | number> = {},
): string {
  const source = messages[locale][key] || messages[DEFAULT_LOCALE][key] || key;
  return source.replace(/\{(\w+)\}/g, (_, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : `{${name}}`,
  );
}

export function translateCategory(locale: Locale, category: string): string {
  const key = categoryKeys[category];
  return key ? translate(locale, key) : category;
}
